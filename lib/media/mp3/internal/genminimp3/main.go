// Command genminimp3 writes the mp3 package's tables from minimp3.h,
// lieff's public-domain (CC0 1.0) MP3 decoder: the Huffman code trees,
// scale factor band widths and partitions, and the constants of its
// stereo processing, antialiasing, IMDCT twiddles and polyphase synthesis. It
// copies each array as minimp3 declares it and checks that the header
// is the one pinned here, so the tables are exactly that commit's.
//
//	curl -LO https://raw.githubusercontent.com/lieff/minimp3/48e3a085f0e1a99446b34614e1e7f17f09dc2e82/minimp3.h
//	genminimp3 -in minimp3.h -out tables_gen.go
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"strings"

	"github.com/stubbedev/lys/lib/atomicfile"
)

const (
	source = "https://github.com/lieff/minimp3"
	commit = "48e3a085f0e1a99446b34614e1e7f17f09dc2e82"
	digest = "eb4b44812cfe77a358aa1820462cc877473a8d97206009ebecd18b60a123875a"
)

// table is one of minimp3's arrays and the name the package gives it.
type table struct{ c, goName string }

var tables = []table{
	{"g_scf_long", "scfLong"},
	{"g_scf_short", "scfShort"},
	{"g_scf_mixed", "scfMixed"},
	{"g_scf_partitions", "scfPartitions"},
	{"g_scfc_decode", "scfcDecode"},
	{"g_mod", "lsfModulus"},
	{"g_preamp", "pretab"},
	{"tabs", "huffTrees"},
	{"tab32", "count1A"},
	{"tab33", "count1B"},
	{"tabindex", "huffTreeAt"},
	{"g_linbits", "linbits"},
	{"g_pan", "intensityPan"},
	{"g_aa", "antialias"},
	{"g_twid9", "twiddle9"},
	{"g_twid3", "twiddle3"},
	{"g_sec", "dctSecant"},
	{"g_win", "synthWindow"},
}

var (
	goTypes = map[string]string{"uint8_t": "uint8", "int16_t": "int16", "float": "float32"}
	dims    = regexp.MustCompile(`^(?:\[[0-9* +]*\])+$`)
	number  = regexp.MustCompile(`^-?(?:[0-9]+\.?[0-9]*|\.[0-9]+)(?:e[-+]?[0-9]+)?f?$`)
)

// declaration finds "static const T name[...] = {" in src and returns
// T, the dimensions and the offset of the opening brace.
func declaration(src, name string) (cType, dimensions string, brace int, err error) {
	re := regexp.MustCompile(`static const (\w+) ` + regexp.QuoteMeta(name) + `((?:\[[^\]]*\])+)\s*=\s*\{`)
	all := re.FindAllStringSubmatchIndex(src, -1)
	if len(all) != 1 {
		return "", "", 0, fmt.Errorf("%s is declared %d times, want once", name, len(all))
	}
	m := all[0]
	return src[m[2]:m[3]], src[m[4]:m[5]], m[1] - 1, nil
}

// rowLength is how many numbers of a flat table go on one line.
const rowLength = 16

// initializer is the braced initializer starting at src[brace] as Go:
// checked to hold nothing but braces, commas and numbers, C's float
// suffixes dropped, one row of a nested table or rowLength numbers of
// a flat one to a line.
func initializer(src string, brace int) (string, error) {
	var tokens []string
	depth := 0
	start := brace
	flush := func(i int) error {
		s := strings.TrimSpace(src[start:i])
		start = i + 1
		if s == "" {
			return nil
		}
		if !number.MatchString(s) {
			return fmt.Errorf("%q in the initializer at offset %d is not a number", s, brace)
		}
		tokens = append(tokens, strings.TrimSuffix(s, "f"))
		return nil
	}
	i := brace
	for ; i < len(src); i++ {
		c := src[i]
		if c != '{' && c != '}' && c != ',' {
			continue
		}
		if err := flush(i); err != nil {
			return "", err
		}
		if c == ',' {
			continue
		}
		tokens = append(tokens, string(c))
		if c == '{' {
			depth++
			continue
		}
		if depth--; depth == 0 {
			break
		}
	}
	if depth != 0 || !strings.HasPrefix(src[i+1:], ";") {
		return "", fmt.Errorf("the initializer at offset %d does not end in \"};\"", brace)
	}
	var b strings.Builder
	depth, column := 0, 0
	for _, t := range tokens {
		switch t {
		case "{":
			depth++
			b.WriteString("{")
			if depth == 1 {
				b.WriteString("\n")
			}
		case "}":
			if depth--; depth == 0 {
				if column > 0 {
					b.WriteString("\n")
				}
				b.WriteString("}")
				continue
			}
			b.WriteString("},\n")
		default:
			if depth > 1 {
				b.WriteString(t + ", ")
				continue
			}
			b.WriteString(t + ",")
			if column++; column == rowLength {
				b.WriteString("\n")
				column = 0
			}
		}
	}
	return b.String(), nil
}

func generate(src []byte) ([]byte, error) {
	sum := sha256.Sum256(src)
	if got := hex.EncodeToString(sum[:]); got != digest {
		return nil, fmt.Errorf("SHA-256 %s, want %s: not minimp3.h of commit %s", got, digest, commit)
	}
	return render(string(src), tables)
}

// render writes the tables of src as Go.
func render(src string, tables []table) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by genminimp3 from minimp3.h of %s at commit %s, public domain under CC0 1.0. DO NOT EDIT.\n\npackage mp3\n\n", source, commit)
	for _, t := range tables {
		cType, dimensions, brace, err := declaration(src, t.c)
		if err != nil {
			return nil, err
		}
		goType, ok := goTypes[cType]
		if !ok {
			return nil, fmt.Errorf("%s is of type %s", t.c, cType)
		}
		if !dims.MatchString(dimensions) {
			return nil, fmt.Errorf("%s has dimensions %s", t.c, dimensions)
		}
		dimensions = strings.Replace(dimensions, "[]", "[...]", 1)
		if strings.Contains(dimensions, "[]") {
			return nil, fmt.Errorf("%s leaves an inner dimension open: %s", t.c, dimensions)
		}
		init, err := initializer(src, brace)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", t.c, err)
		}
		fmt.Fprintf(&b, "var %s = %s%s%s\n\n", t.goName, dimensions, goType, init)
	}
	return format.Source(b.Bytes())
}

func main() {
	in := flag.String("in", "minimp3.h", "path of minimp3.h")
	out := flag.String("out", "tables_gen.go", "file to write")
	flag.Parse()
	src, err := os.ReadFile(*in)
	if err != nil {
		log.Fatalf("genminimp3: %v", err)
	}
	text, err := generate(src)
	if err != nil {
		log.Fatalf("genminimp3: %s: %v", *in, err)
	}
	if err := atomicfile.WriteFile(*out, text, 0o644); err != nil {
		log.Fatalf("genminimp3: %v", err)
	}
}
