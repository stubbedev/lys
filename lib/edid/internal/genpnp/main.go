// Command genpnp writes the edid package's PNP ID table from hwdata's
// pnp.ids, the UEFI PNP ID registry's three-letter manufacturer IDs and
// names, sorted by ID so the package finds a name by binary search. An
// ID no EDID can encode, five bits a letter from '@', is left out.
//
//	genpnp -ids pnp.ids -out pnp_gen.go
package main

import (
	"bytes"
	"cmp"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
	"strings"
	"unicode/utf8"

	"github.com/stubbedev/lys/lib/atomicfile"
)

type vendor struct{ id, name string }

func parse(src []byte) (vendors []vendor, unencodable []string, err error) {
	for n, line := range strings.Split(strings.TrimSuffix(string(src), "\n"), "\n") {
		id, name, ok := strings.Cut(line, "\t")
		name = strings.TrimSpace(name)
		if !ok || len(id) != 3 || name == "" || !utf8.ValidString(name) {
			return nil, nil, fmt.Errorf("line %d is not a PNP ID, a tab and a name: %q", n+1, line)
		}
		if !encodable(id) {
			unencodable = append(unencodable, id)
			continue
		}
		vendors = append(vendors, vendor{id, name})
	}
	slices.SortStableFunc(vendors, func(a, b vendor) int { return cmp.Compare(a.id, b.id) })
	for i := 1; i < len(vendors); i++ {
		if vendors[i].id == vendors[i-1].id {
			return nil, nil, fmt.Errorf("%s is listed twice: %q and %q", vendors[i].id, vendors[i-1].name, vendors[i].name)
		}
	}
	return vendors, unencodable, nil
}

func encodable(id string) bool {
	for _, c := range []byte(id) {
		if c < '@' || c > '@'+0x1f {
			return false
		}
	}
	return true
}

func generate(src []byte) (text []byte, unencodable []string, err error) {
	vendors, unencodable, err := parse(src)
	if err != nil {
		return nil, nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by genpnp. DO NOT EDIT.\n\npackage edid\n\nvar vendors = [...]vendor{\n")
	for _, v := range vendors {
		fmt.Fprintf(&b, "\t{%q, %q},\n", v.id, v.name)
	}
	b.WriteString("}\n")
	text, err = format.Source(b.Bytes())
	return text, unencodable, err
}

func main() {
	ids := flag.String("ids", os.Getenv("LYS_HWDATA_PNP_IDS"), "path of hwdata's pnp.ids")
	out := flag.String("out", "pnp_gen.go", "file to write")
	flag.Parse()
	if *ids == "" {
		log.Fatal("genpnp: -ids or LYS_HWDATA_PNP_IDS is required")
	}
	src, err := os.ReadFile(*ids) //nolint:gosec // the path the generator was given
	if err != nil {
		log.Fatalf("genpnp: %v", err)
	}
	text, unencodable, err := generate(src)
	if err != nil {
		log.Fatalf("genpnp: %s: %v", *ids, err) //nolint:gosec // the path the generator was given
	}
	for _, id := range unencodable {
		log.Printf("genpnp: %s: %q is left out: an EDID manufacturer ID encodes only '@' to '_'", *ids, id) //nolint:gosec // the path the generator was given
	}
	if err := atomicfile.WriteFile(*out, text, 0o644); err != nil {
		log.Fatalf("genpnp: %v", err)
	}
}
